class Doctor {
  final String id;
  final String name;
  final String specialization;
  final String imageUrl;
  final String bio;
  final String email;
  final String phoneNumber;


  Doctor({
    required this.id,
    required this.name,
    required this.specialization,
    required this.imageUrl,
    required this.bio,
    required this.email,
    required this.phoneNumber,
  });
}


