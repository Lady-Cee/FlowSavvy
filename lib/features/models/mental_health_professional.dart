  final String id;
  final String name;
  final String expertise;
  final String imageUrl;
  final String bio;
  final String email;
  final String phoneNumber;

  MentalHealthProfessional({
    required this.id,
    required this.name,
    required this.expertise,
    required this.imageUrl,
    required this.bio,
    required this.email,
    required this.phoneNumber,
  });
}
